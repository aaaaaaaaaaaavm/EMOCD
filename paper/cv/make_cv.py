def main():
    f = facts()
    missing = [k for k, v in f.items() if v is None]
    if missing:
        raise SystemExit(
            "Missing keys in analysis/results/*.json: " + ", ".join(missing) +
            "\nThe CV will not be written with blanks. Fix the lookup in facts() instead."
        )

    # LaTeX is full of % and \%, which Python's %-formatting cannot survive. Tokens instead.
    subs = {
        "@V_EXIT@":    f"{f['v_exit']:.1f}",
        "@V_FAM_LO@":  f"{f['v_fam_lo']:.1f}",
        "@V_FAM_HI@":  f"{f['v_fam_hi']:.1f}",
        "@A_PEAK_G@":  f"{f['a_peak_g']:.1f}",
        "@ENERGY_KJ@": f"{f['energy_kJ']:.2f}",
        "@KT@":        f"{f['kt']:.2f}",
        "@MASS_DRY@":  f"{f['mass_dry']:.0f}",
    }
    out = TEMPLATE
    for k, v in subs.items():
        out = out.replace(k, v)
    left = re.findall(r"@[A-Z_]+@", out)
    if left:
        raise SystemExit("Unsubstituted tokens remain: " + ", ".join(sorted(set(left))))

    dest = os.path.join(HERE, "cv.tex")
    with open(dest, "w") as fh:
        fh.write(out)

    print("CV numbers taken from analysis/results/:")
    for k in ("v_exit", "a_peak_g", "energy_kJ", "kt", "v_fam_lo", "v_fam_hi",
              "mass_dry", "mass_wet", "sled_kg", "disp_3sig", "midgap_T"):
        print(f"  {k:12s} {f[k]}")
    print(f"\n-> {os.path.relpath(dest)}")
    print("   build:  cd paper/cv && pdflatex cv.tex")


if __name__ == "__main__":
    main()

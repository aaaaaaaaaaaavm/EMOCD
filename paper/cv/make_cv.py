HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "..", "..", "analysis", "results")


def load(name):
    with open(os.path.join(RESULTS, name)) as f:
        return json.load(f)


def facts():
    motor = load("motor_results.json")
    sizing = load("sizing.json")
    mass = load("mass_properties.json")
    field = load("field_verification.json")

    shot = motor["shot"]
    fam = motor["family"]

    f = {
        "v_exit": shot["v_exit"],
        "a_peak_g": shot["a_g"],
        "energy_kJ": sizing["energy_closure"]["drawn_net_J"] / 1000.0,
        "kt": motor["Kt_N_per_kA"],
        "v_fam_lo": min(v["v_exit"] for v in fam.values()),
        "v_fam_hi": max(v["v_exit"] for v in fam.values()),
        "midgap_T": field["double_midgap_peak_T"],
    }
    # Mass and dispersion keys have moved before; look them up defensively and report what is
    # missing rather than silently emitting a blank.
    for key, src, names in (
        ("mass_dry", mass, ("dry_kg",)),
        ("mass_wet", mass, ("loaded_kg",)),
        ("sled_kg", mass, ("sled_kg",)),
        ("disp_3sig", motor, ("closed_loop_3sigma",)),
    ):
        f[key] = next((src[n] for n in names if n in src), None)
    return f



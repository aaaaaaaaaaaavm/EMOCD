ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The shared cross-link block. Byte-identical in all four repositories -- the flagship's copy
# in PROGRAMME.md is the source, and this is checked by tools/check_links.py.
HEADER_ROWS = [
    ("VOLLEY", "Flagship: the authoritative engineering record, and the portfolio", ""),
    ("VOLLEY-paper", "IEEE companion: manuscript and reproducibility package *(generated)*", "paper"),
    ("VOLLEY-thesis", "Thesis companion: university submission *(generated)*", "thesis"),
    ("VOLLEY-lab", "Phase II: research, redesign, deliberately unstable", "lab"),
]
OWNER = "aaaaaaaaaaaavm"

# The generated directory name has to match the repository it is pushed to. Override it if the
# repositories have not been renamed yet:
#
#     REPO_PREFIX=EMOCD python3 tools/export_companion.py --out ../companions
#
# Getting this wrong does not fail loudly. `gh repo create` in bootstrap_repos.sh would simply
# create a second, empty repository under the other name and push to that, leaving the real one
# untouched and the mistake invisible until someone opens the wrong URL.
REPO_PREFIX = os.environ.get("REPO_PREFIX", "VOLLEY")
# The flagship repository these are generated from. Follows REPO_PREFIX so the
# provenance banner cannot point at a repository name that no longer exists.
FLAGSHIP = REPO_PREFIX


def header_table(here):
    """`here` is '', 'paper', 'thesis' or 'lab'."""
    out = ["<!-- PROGRAMME-HEADER-START -->",
           "| Repository | Role | You are here |", "|---|---|---|"]
    for name, role, key in HEADER_ROWS:
        link = f"[{name}](https://github.com/{OWNER}/{name})"
        cell = f"**{link}**" if key == here else link
        out.append(f"| {cell} | {role} | {'←' if key == here else ''} |")
    out.append("<!-- PROGRAMME-HEADER-END -->")
    return "\n".join(out)


def banner(commit, kind):
    return f"""> ## Generated repository, do not edit here
>
> Every file in this repository is generated from the **VOLLEY flagship** by
> `tools/export_companion.py`. Nothing here is authored, and any edit made here will be
> destroyed the next time it is regenerated.
>
> **Source:** [{OWNER}/{FLAGSHIP}](https://github.com/{OWNER}/{FLAGSHIP}) at commit `{commit}`
> **Found a mistake?** Fix it in the flagship. This repository will pick it up.
>
> The flagship is the authoritative engineering record. Where this repository and the
> flagship disagree, the flagship is right and this copy is stale.

{header_table(kind)}
"""



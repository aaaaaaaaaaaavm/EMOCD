def copy(src, dst):
    s, d = os.path.join(ROOT, src), os.path.join(dst)
    os.makedirs(os.path.dirname(d) or d, exist_ok=True)
    if os.path.isdir(s):
        shutil.copytree(s, d, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns('__pycache__', '*.pyc', 'output'))
    elif os.path.exists(s):
        shutil.copy2(s, d)
    else:
        print(f"    MISSING (skipped): {src}")
        return 0
    return 1


def build(kind, manifest, readme, out_root, commit):
    dest = os.path.join(out_root, f"{REPO_PREFIX}-{kind}")
    if os.path.exists(dest):
        shutil.rmtree(dest)          # regenerate wholesale; never merge into a stale tree
    os.makedirs(dest)
    n = sum(copy(src, os.path.join(dest, rel)) for src, rel in manifest)
    with open(os.path.join(dest, "README.md"), "w") as f:
        f.write(banner(commit, kind) + "\n---\n\n" + readme)
    with open(os.path.join(dest, ".gitignore"), "w") as f:
        f.write("__pycache__/\n*.pyc\n*.aux\n*.log\n*.out\npaper.pdf\n")
    if kind == "thesis":
        os.makedirs(os.path.join(dest, "university"), exist_ok=True)
        with open(os.path.join(dest, "university", "README.md"), "w") as f:
            f.write("# University-specific material\n\n"
                    "**This directory is never touched by `export_companion.py`.** Submission "
                    "forms, templates, formatting mandates and viva material go here.\n\n"
                    "Everything outside this directory is generated and will be overwritten "
                    "on the next export.\n")
    print(f"  VOLLEY-{kind}: {n} paths -> {dest}")
    return dest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="directory to write the companions into")
    ap.add_argument("--only", choices=["paper", "thesis"], help="build just one")
    args = ap.parse_args()

    dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT,
                           capture_output=True, text=True).stdout.strip()
    if dirty:
        print("WARNING: flagship working tree is dirty. The companions will record a commit "
              "that does not match what was copied. Commit first.\n", file=sys.stderr)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                            capture_output=True, text=True).stdout.strip()

    out_root = os.path.abspath(args.out)
    os.makedirs(out_root, exist_ok=True)
    print(f"generating companions from flagship {commit} into {out_root}")
    if args.only in (None, "paper"):
        build("paper", PAPER_MANIFEST, PAPER_README, out_root, commit)
    if args.only in (None, "thesis"):
        build("thesis", THESIS_MANIFEST, THESIS_README, out_root, commit)
    print("done. These are output -- do not edit them; edit the flagship and re-run.")


if __name__ == "__main__":
    main()
